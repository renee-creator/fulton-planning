"""Pages loaded only when opened. A part of src/app.html marked with /*__LAZY_BEGIN name entries__*/ and
/*__LAZY_END name__*/ is split in two at build time. What the rest of TREE uses stays in the page, with everything it
reaches inside the part. The rest goes to tree-<name>.js, which the page loads the first time one of the entries is
called, such as renderKitchen when the Kitchen page opens. Each entry is left in the page as a small function that
loads the file and then calls the entry the file brings. Used by tools/build.py."""
import re, hashlib

DECL = re.compile(r'(?:async\s+)?function\s+([A-Za-z_$][\w$]*)\s*\(|(?:let|const|var)\s+')


def _names(stmt):
    """the names a let, const or var line declares, reading its declarators at the top level only"""
    m = re.match(r'(?:let|const|var)\s+', stmt)
    if not m:
        return []
    out, depth, i, start, q = [], 0, m.end(), m.end(), None
    while i < len(stmt):
        c = stmt[i]
        if q:
            if c == '\\':
                i += 2; continue
            if c == q:
                q = None
        elif c in '"\'`':
            q = c
        elif c in '([{':
            depth += 1
        elif c in ')]}':
            depth -= 1
        elif depth == 0 and c in ',;':
            out.append(stmt[start:i]); start = i + 1
            if c == ';':
                break
        i += 1
    else:
        out.append(stmt[start:])
    names = []
    for part in out:
        mm = re.match(r'\s*([A-Za-z_$][\w$]*)', part)
        if mm:
            names.append(mm.group(1))
    return names


def _chunks(text):
    """the part, cut at each declaration that starts a line"""
    chunks, cur = [], None
    for line in text.split('\n'):
        m = DECL.match(line) if line and not line[0].isspace() else None
        if m:
            cur = {'names': set([m.group(1)] if m.group(1) else _names(line)), 'text': ''}
            chunks.append(cur)
        if cur is None:
            cur = {'names': set(), 'text': ''}
            chunks.append(cur)
        cur['text'] += line + '\n'
    return chunks


def _uses(name, text):
    return re.search(r'(?<![\w$.])' + re.escape(name) + r'(?![\w$])', text) is not None


def split(app, others):
    """returns the page with each marked part split, and the files to write, {file name: text}"""
    files = {}
    rx = re.compile(r'/\*__LAZY_BEGIN (\w+) ([\w$,]+)__\*/\n(.*?)/\*__LAZY_END \1__\*/\n', re.S)
    parts = list(rx.finditer(app))
    helper_done = False
    out, last = [], 0
    for m in parts:
        name, entries, body = m.group(1), m.group(2).split(','), m.group(3)
        outside = app[:m.start()] + app[m.end():] + '\n' + others
        chunks = _chunks(body)
        allnames = set().union(*[c['names'] for c in chunks]) if chunks else set()
        keep = set(n for n in allnames if n not in entries and _uses(n, outside))
        changed = True
        while changed:
            changed = False
            for c in chunks:
                if c['names'] & keep:
                    for n in allnames - keep:
                        if n not in entries and _uses(n, c['text']):
                            keep.add(n); changed = True
        # a statement run when the page loads, such as a timer or the start of TREE, never moves to a file loaded later
        for c in chunks:
            if c['names'] & keep:
                continue
            for line in c['text'].split('\n'):
                bad = re.match(r'(setInterval|setTimeout|boot|queueMicrotask|requestAnimationFrame)\s*\(|\$\(|\{|(?!document\.|window\.)[A-Za-z_$][\w$.]*\s*\(', line)
                assert not bad or re.match(r'(document|window)\.addEventListener', line), name + ' would run later: ' + line[:80]
        stay = ''.join(c['text'] for c in chunks if c['names'] & keep)
        later = ''.join(c['text'] for c in chunks if not (c['names'] & keep))
        # an entry the page still keeps would be both in the page and in the file
        for e in entries:
            assert e in allnames and not any(e in c['names'] for c in chunks if c['names'] & keep), e
        js = ('/* Generated by tools/build.py from the part of src/app.html marked ' + name + '. Do not edit this file. Change src/app.html and build again. */\n'
              + later + 'window.TreeLazy_' + name + '=true;\n')
        v = hashlib.sha1(js.encode()).hexdigest()[:10]
        files['tree-' + name + '.js'] = js
        stub = ''
        if not helper_done:
            stub += ('// pages loaded only when opened. tools/build.py moves what only these pages use to their own files\n'
                     'const LAZY_LOAD={};function lazyLoad(n,v){return LAZY_LOAD[n]=LAZY_LOAD[n]||loadScript("tree-"+n+".js?v="+v,"TreeLazy_"+n).catch(e=>{LAZY_LOAD[n]=null;throw e})}\n')
            helper_done = True
        for e in entries:
            if e.startswith('render'):
                stub += ('function ' + e + '(...a){const m=$("#main");if(m&&!window.TreeLazy_' + name + ')m.innerHTML=\'<div class="empty"><span class="spin"></span> Opening</div>\';'
                         'return lazyLoad("' + name + '","' + v + '").then(()=>' + e + '(...a),()=>{if(m)m.innerHTML=\'<div class="empty">This page could not open. Check the connection and try again.</div>\'})}\n')
            else:
                stub += 'function ' + e + '(...a){return lazyLoad("' + name + '","' + v + '").then(()=>' + e + '(...a))}\n'
        out.append(app[last:m.start()]); out.append(stay + stub); last = m.end()
    out.append(app[last:])
    return ''.join(out), files

'use strict';
// Session 11, speed. The Kitchen, the newsletter, the grant and Settings load only when opened, and the pages that read
// the same calendar days share one request. Made-up names only.
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs'), path = require('path');
const { start, browser } = require('./fixture.js');
const ROOT = path.join(__dirname, '..');

test('four pages are their own files, loaded when opened', () => {
  const tree = fs.readFileSync(path.join(ROOT, 'tree.html'), 'utf8');
  for (const n of ['kitchen', 'newsletter', 'grant', 'settings']) {
    const f = fs.readFileSync(path.join(ROOT, 'tree-' + n + '.js'), 'utf8');
    assert.ok(f.startsWith('/* Generated by tools/build.py'), n);
    assert.match(f, new RegExp('window\\.TreeLazy_' + n + '=true;\\n$'));
    assert.match(tree, new RegExp('lazyLoad\\("' + n + '","[0-9a-f]{10}"\\)'));
  }
  assert.doesNotMatch(tree, /__LAZY_(BEGIN|END)/);
  assert.match(tree, /function renderKitchen\(\.\.\.a\)\{/);
  assert.doesNotMatch(tree, /function renderKitchen\(\)\{/, 'the Kitchen page itself is in tree-kitchen.js');
  // one calendar request, shared
  assert.strictEqual((tree.match(/FP_API\("\/api\/view"/g) || []).length, 1);
});

test('each page loaded later opens, for the director and the kitchen', async t => {
  const chromium = await browser(); if (!chromium) { t.skip('Playwright is not installed here'); return; }
  const fx = await start({ more: put => put('menus/2026-10.json', { id: '2026-10', month: '2026-10', days: {}, notes: {} }) });
  const b = await chromium.launch();
  t.after(async () => { await b.close(); await fx.stop(); });
  const open = async (name, pass) => { const j = await fx.login(name, pass); const ctx = await b.newContext({ viewport: { width: 1200, height: 800 } }); const p = await ctx.newPage(); const errors = []; p.on('pageerror', e => errors.push(e.message));
    await p.addInitScript(([t, n]) => { localStorage.setItem('fp-token', t); localStorage.setItem('fp-name', n); }, [j.token, j.name]);
    await p.goto(fx.page); await p.waitForFunction(() => typeof goView === 'function' && window.FP_NAME && window.FP_NAME(), null, { timeout: 15000 }); await p.waitForTimeout(1200); return { p, errors }; };
  const d = await open('Dee', 'director-pass-1');
  const seen = { kitchen: /menu/, newsletter: /Family newsletter/, grant: /GRANT/i, settings: /Program settings/ };
  for (const [v, re] of Object.entries(seen)) {
    await d.p.evaluate(v => goView(v), v);
    await d.p.waitForFunction(re => new RegExp(re, 'i').test(document.getElementById('main').innerText), re.source, { timeout: 15000 });
    assert.ok(await d.p.evaluate(v => !!window['TreeLazy_' + v], v), v + ' loaded');
  }
  assert.deepStrictEqual(d.errors, []);
  const k = await open('Kit', '1357');
  await k.p.waitForFunction(() => /menu/.test(document.getElementById('main').innerText), null, { timeout: 15000 });
  assert.deepStrictEqual(k.errors, []);
});
